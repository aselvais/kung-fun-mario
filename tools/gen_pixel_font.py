def main():
    chars = list(GLYPHS.keys())
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    cell = 8
    img = Image.new("RGBA", (cols * cell, rows * cell), (0, 0, 0, 0))
    pix = img.load()
    lines = [
        'info face="Pixel8" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight=8 base=7 scaleW={img.width} scaleH={img.height} pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4",
        'page id=0 file="pixel_8.png"',
        f"chars count={len(chars)}",
    ]
    for i, ch in enumerate(chars):
        cx = (i % cols) * cell
        cy = (i // cols) * cell
        pattern = GLYPHS[ch]
        for y, row in enumerate(pattern):
            for x, bit in enumerate(row):
                if bit == "#":
                    pix[cx + x, cy + y] = WHITE
        cid = ord(ch)
        w = 0 if ch == " " else 7
        adv = 6 if ch == " " else 8
        lines.append(
            f"char id={cid} x={cx} y={cy} width={w if ch == ' ' else 8} height=8 "
            f"xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15"
        )
    img.save(OUT / "pixel_8.png")
    (OUT / "pixel.fnt").write_text("\n".join(lines) + "\n")
    print("wrote", OUT / "pixel.fnt", "and", OUT / "pixel_8.png", img.size)


if __name__ == "__main__":
    main()
